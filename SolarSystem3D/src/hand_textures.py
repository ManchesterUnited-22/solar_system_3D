def moon_texture(out_w=2048, out_h=1024, seed=3):
    rng = np.random.default_rng(seed)
    W, H = out_w, out_h
    cv = _Canvas(W, H)
    n_mid, n_fine = _fbm(rng, W, H, 30, 4), _fbm(rng, W, H, 160, 3)
