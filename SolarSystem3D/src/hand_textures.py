def _smooth(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def _mix(a, b, t):
    """Tron mau a->b theo trong so t (H,W). a, b: (3,) hoac (H,W,3)."""
    a = np.asarray(a, dtype=np.float32)
    b = np.asarray(b, dtype=np.float32)
    t = t[..., None].astype(np.float32)
    return a * (1.0 - t) + b * t


class _Canvas:
    """Khung ve toa do kinh/vi do -> pixel (equirectangular)."""

    def __init__(self, W, H):
        self.W, self.H = W, H

    def xy(self, lon, lat):
        return ((lon + 180.0) / 360.0 * self.W, (90.0 - lat) / 180.0 * self.H)

    def layer(self, polys=(), lines=(), line_w=1.0, blur=0.0, fill=255):
        """Ve cac da giac / duong gap khuc len anh xam, tra ve float 0..1."""
        im = Image.new("L", (self.W, self.H), 0)
        d = ImageDraw.Draw(im)
        for p in polys:
            d.polygon([self.xy(*q) for q in p], fill=fill)
        for pts, w in lines:
            px = [self.xy(*q) for q in pts]
            wpx = max(1, int(w / 360.0 * self.W))
            d.line(px, fill=fill, width=wpx, joint="curve")
            r = wpx / 2.0                       # bo tron hai dau
            for x, y in (px[0], px[-1]):
                d.ellipse([x - r, y - r, x + r, y + r], fill=fill)
        if blur > 0:
            im = im.filter(ImageFilter.GaussianBlur(blur))
        return np.asarray(im, dtype=np.float32) / 255.0


def _noise(rng, W, H, cells):
    """Value-noise khop kin theo chieu ngang (khong lo duong noi)."""
    gy = max(2, cells // 2)
    g = rng.random((gy + 1, cells)).astype(np.float32)
    g = np.tile(g, (1, 3))
    im = Image.fromarray(g, mode="F").resize((3 * W, H), Image.BICUBIC)
    return np.asarray(im)[:, W:2 * W].copy()


def _fbm(rng, W, H, base, octaves, pers=0.5):
    tot = np.zeros((H, W), np.float32)
    amp, norm = 1.0, 0.0
    for o in range(octaves):
        tot += amp * _noise(rng, W, H, base * 2 ** o)
        norm += amp
        amp *= pers
    tot /= norm
    return (tot - tot.min()) / (tot.max() - tot.min() + 1e-9)


def _mid(a, b, rng, depth, rough):
    """Chia doi canh a-b, day diem giua lech ngang -> duong bo gap ghenh (midpoint displacement)."""
    dx, dy = b[0] - a[0], b[1] - a[1]
    L = (dx * dx + dy * dy) ** 0.5
    seam = (abs(a[0]) == 180 and abs(b[0]) == 180) or (a[1] == -90 and b[1] == -90)
    if depth == 0 or L < 0.35 or seam:
        return [a]
    off = rng.normal(0.0, rough * L * 0.5)
    m = ((a[0] + b[0]) / 2 - dy / L * off, (a[1] + b[1]) / 2 + dx / L * off)
    return _mid(a, m, rng, depth - 1, rough) + _mid(m, b, rng, depth - 1, rough)


def _fractal(pts, rng, depth=4, rough=0.2, closed=True):
    pts = [tuple(p) for p in pts]
    n = len(pts)
    out = []
    for i in range(n if closed else n - 1):
        out.extend(_mid(pts[i], pts[(i + 1) % n], rng, depth, rough))
    if not closed:
        out.append(pts[-1])
    return out


