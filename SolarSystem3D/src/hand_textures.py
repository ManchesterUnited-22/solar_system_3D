def _storm(img, cv, rng, lon, la, rx, ry, col, collar=None, blur=0.8):
    W = img.shape[1]
    if collar is not None:
        c = cv.layer(polys=[_ellipse(lon, la, rx * 1.35, ry * 1.4)], blur=blur * 2.0 * W / 360.0)
        img[:] = _mix(img, collar, np.clip(c * 1.3, 0, 1) * 0.7)
    m = cv.layer(polys=[_fractal(_ellipse(lon, la, rx, ry), rng, 3, 0.10)], blur=blur * W / 360.0)
    img[:] = _mix(img, col, np.clip(m * 1.4, 0, 1))


