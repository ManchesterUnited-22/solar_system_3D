def _gauss_blur_fft(a, sx, sy):
    """Lam mo gaussian bang FFT (khep kin 2 chieu -> khong lo duong noi texture)."""
    H, W = a.shape
    fy = np.fft.fftfreq(H)[:, None]
    fx = np.fft.rfftfreq(W)[None, :]
    k = np.exp(-2.0 * np.pi ** 2 * ((sx * fx) ** 2 + (sy * fy) ** 2)).astype(np.float32)
    return np.maximum(np.fft.irfft2(np.fft.rfft2(a) * k, s=a.shape), 0.0).astype(np.float32)


def earth_lights_texture(out_w=4096, out_h=2048, seed=5):
    """Den do thi ban dem -> mang float (out_h, out_w, 3) 0..1, hang 0 = cuc Nam.

    Dung CHINH mat na dat cua texture ngay (cung seed, cung do phan giai noi bo 2x) nen den
    luon nam tren luc dia. Dung voi blend cong (GL_ONE, GL_ONE) tren nen toi.
    """
    W, H = out_w, out_h
    assert (W, H) == (4096, 2048), "mat na dat chi khop tuyet doi voi texture ngay o 4096x2048"
    rng_land = np.random.default_rng(seed)
    cv = _Canvas(W, H)
    land = _earth_land(rng_land, cv, W, H, W / 360.0)

    # cho phep sai lech nhe o bo bien (ban do ve tay) de thanh pho ven bien khong bi mat
    ok = _gauss_blur_fft(land, 3.5, 3.5) > 0.30
    rng = np.random.default_rng(seed + 101)
    px_deg = W / 360.0

    def to_px(lon, lat):
        return (lon + 180.0) * px_deg, (90.0 - lat) * px_deg

    X, Y, B, S = [], [], [], []

    def add(lon, lat, b, s):
        lon = np.asarray(lon); lat = np.asarray(lat)
        x, y = to_px(lon, lat)
        xi = np.clip(np.rint(x).astype(int), 0, W - 1)
        yi = np.clip(np.rint(y).astype(int), 0, H - 1)
        keep = ok[yi, xi] & (lat < 71.0) & (lat > -56.0)
        X.append(x[keep]); Y.append(y[keep]); B.append(b[keep]); S.append(s[keep])
        return keep

    # --- vung dan cu: thi tran rai rac + loi sieu do thi ---
    for lon, lat, sx, sy, w in CITY_REGIONS:
        n = int(w * sx * sy * 120) + 8
        # 70% tap trung, 30% ngoai o (vanh dai do thi)
        spread = np.where(rng.random(n) < 0.7, 1.0, 2.1)
        lo = lon + rng.normal(0, sx, n) * spread
        la = lat + rng.normal(0, sy, n) * spread
        b = np.exp(rng.normal(-1.15, 0.65, n)) * (0.30 + 0.75 * w)
        b *= 1.0 + 4.0 * rng.random(n) ** 10             # thinh thoang co o that sang
        add(lo, la, b, 0.50 + 0.22 * rng.random(n))
        if sx <= 1.6 and w >= 0.3:                         # loi sieu do thi: meo, keo dai, khong tron
            m = int(45 + 200 * w * w)
            a0 = rng.uniform(0, np.pi)
            asp = rng.uniform(1.0, 2.6)
            u = rng.normal(0, 1, m) * asp
            v = rng.normal(0, 1, m) / np.sqrt(asp)
            rr = np.hypot(u, v)
            lo = lon + (u * np.cos(a0) - v * np.sin(a0)) * sx * 0.17
            la = lat + (u * np.sin(a0) + v * np.cos(a0)) * sy * 0.17
            b = (0.28 + 0.55 * w) * np.exp(-rr * 0.30) * np.exp(rng.normal(0, 0.42, m))
            add(lo, la, b, 0.44 + 0.14 * rng.random(m))

    # --- hanh lang do thi: sang dan doc cao toc/dai do thi ---
    for pts, w in CORRIDORS:
        pts = np.array(pts, float)
        seg = np.diff(pts, axis=0)
        L = np.hypot(seg[:, 0], seg[:, 1])
        for i in range(len(seg)):
            n = int(L[i] * 38 * (0.30 + w)) + 4
            t = rng.random(n)
            lo = pts[i, 0] + seg[i, 0] * t + rng.normal(0, 0.20, n)
            la = pts[i, 1] + seg[i, 1] * t + rng.normal(0, 0.20, n)
            b = np.exp(rng.normal(-1.3, 0.55, n)) * (0.25 + 0.55 * w)
            add(lo, la, b, 0.46 + 0.16 * rng.random(n))

    X = np.concatenate(X).astype(np.float32); Y = np.concatenate(Y).astype(np.float32)
    B = np.concatenate(B).astype(np.float32); S = np.concatenate(S).astype(np.float32)

    # --- ve tung diem sang: gaussian lech de bu meo equirectangular (rong hon o vi do cao) ---
    lat_pt = 90.0 - Y / px_deg
    sy = S
    sx = np.clip(S / np.maximum(np.cos(np.radians(lat_pt)), 0.30), 0.0, 2.6)
    acc = np.zeros(H * W, np.float32)
    OFF_Y, OFF_X = range(-3, 4), range(-6, 7)
    CH = 25000
    for c0 in range(0, len(X), CH):
        x, y, b = X[c0:c0 + CH], Y[c0:c0 + CH], B[c0:c0 + CH]
        sxc, syc = sx[c0:c0 + CH], sy[c0:c0 + CH]
        ix, iy = np.rint(x).astype(np.int64), np.rint(y).astype(np.int64)
        idx_all, w_all = [], []
        for oy in OFF_Y:
            for ox in OFF_X:
                px_, py_ = ix + ox, iy + oy
                v = (py_ >= 0) & (py_ < H)
                d2 = ((px_ - x) / sxc) ** 2 + ((py_ - y) / syc) ** 2
                w = b * np.exp(-0.5 * d2)
                idx_all.append((py_[v] * W + (px_[v] % W)))
                w_all.append(w[v])
        acc += np.bincount(np.concatenate(idx_all), np.concatenate(w_all),
                           minlength=H * W).astype(np.float32)
    acc = acc.reshape(H, W)

    # --- quang: loi sang + quang vua + vang toa rong (anh sang tan trong khi quyen) ---
    mid = _gauss_blur_fft(acc, 3.0, 2.1)
    wide = _gauss_blur_fft(acc, 12.0, 8.5)
    core = 1.0 - np.exp(-(acc * 0.85 + mid * 2.0))
    halo = 1.0 - np.exp(-(wide * 18.0))

    # --- mau: cam natri o vung thua -> vang am -> trang am o loi sieu do thi ---
    t = np.clip(core, 0, 1)[..., None]
    c_low = np.array((0.95, 0.38, 0.07), np.float32)
    c_mid = np.array((1.00, 0.70, 0.26), np.float32)
    c_hi = np.array((1.00, 0.93, 0.74), np.float32)
    ramp = np.where(t < 0.55, c_low + (c_mid - c_low) * (t / 0.55),
                    c_mid + (c_hi - c_mid) * np.clip((t - 0.55) / 0.45, 0, 1))
    img = ramp * (core ** 0.9)[..., None]
    img += np.array((1.0, 0.40, 0.09), np.float32) * (halo * 0.075)[..., None]

    img = np.clip(img, 0, 1).astype(np.float32)
    return np.ascontiguousarray(img[::-1])           # hang 0 = cuc Nam, giong earth_texture


