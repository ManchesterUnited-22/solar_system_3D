    img *= (0.90 + 0.20 * n_fine)[..., None]
    _craters(img, rng, 3600, 0.22, 4.5, 0.24, 0.10)
    ray = np.zeros((H, W), np.float32)
    for lon, lat in [(-31, 11), (100, -40), (-120, -30), (60, 62)]:
        for _ in range(16):
            a = rng.uniform(0, 2 * np.pi)
            L = rng.uniform(6, 22)
            p = [(lon, lat), (lon + np.cos(a) * L / max(np.cos(np.radians(lat)), 0.3), lat + np.sin(a) * L)]
            ray = np.maximum(ray, cv.layer(lines=[(p, 0.3)], blur=1.0) * rng.uniform(0.4, 1.0))
    img = _mix(img, (0.80, 0.77, 0.72), ray * 0.45)
    return _finish(img)


