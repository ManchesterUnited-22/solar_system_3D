def _noise2(rng, W, H, gx, gy):
    """Noise khong dang huong: gx o ngang, gy o doc (dai song / vet keo dai)."""
    g = rng.random((gy + 1, gx)).astype(np.float32)
    g = np.tile(g, (1, 3))
    im = Image.fromarray(g, mode="F").resize((3 * W, H), Image.BICUBIC)
    return np.asarray(im)[:, W:2 * W].copy()


def _ellipse(lon, lat, rx, ry, rot=0.0, n=40):
    """Da giac elip tren mat cau: rx, ry la ban kinh cung (do)."""
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    c, sn = np.cos(np.radians(rot)), np.sin(np.radians(rot))
    x, y = rx * np.cos(t), ry * np.sin(t)
    k = max(np.cos(np.radians(lat)), 0.25)
    return [(lon + (a * c - b * sn) / k, lat + (a * sn + b * c)) for a, b in zip(x, y)]


def _finish(img):
    return np.ascontiguousarray(np.clip(img, 0, 1)[::-1])


def _craters(img, rng, n, rmin, rmax, depth=0.30, rim=0.10):
    """Ho thien thach (ban kinh tinh theo do cung), nhieu ho nho, it ho lon."""
    H, W, _ = img.shape
    for _ in range(n):
        r = rmin * (rmax / rmin) ** (rng.random() ** 2.4)
        lon = rng.uniform(-180, 180)
        lat = np.degrees(np.arcsin(rng.uniform(-0.97, 0.97)))
        cx, cy = (lon + 180) / 360 * W, (90 - lat) / 180 * H
        ry = max(r / 180 * H, 1.5)
        rx = max(r / max(np.cos(np.radians(lat)), 0.2) / 360 * W, 1.5)
        x0, x1 = int(cx - rx * 1.6), int(cx + rx * 1.6) + 1
        y0, y1 = max(int(cy - ry * 1.6), 0), min(int(cy + ry * 1.6) + 1, H)
        if y1 <= y0:
            continue
        xi, yi = np.arange(x0, x1) % W, np.arange(y0, y1)
        xx, yy = np.meshgrid(np.arange(x0, x1), yi)
        u, v = (xx - cx) / rx, (yy - cy) / ry
        d = np.hypot(u, v)
        floor = np.clip(1.0 - d, 0, 1) ** 0.5
        wall = np.exp(-((d - 1.0) / 0.16) ** 2)
        lit = np.clip(-(u + v) * 0.5, -1, 1)                # thanh ho phia Tay Bac sang hon
        sub = img[np.ix_(yi, xi)]
        sub = sub * (1.0 - depth * floor)[..., None] + (rim * wall * (0.6 + 0.8 * lit))[..., None]
        img[np.ix_(yi, xi)] = sub


def _bands(rng, W, H, table, warp=2.5, festoon=None, streak=0.10):
    """To mau theo dai vi do (bang noi suy), co uon luon + sọc keo dai theo kinh tuyen."""
    lat = np.linspace(90, -90, H, dtype=np.float32)[:, None] * np.ones((1, W), np.float32)
    lon = np.linspace(-np.pi, np.pi, W, dtype=np.float32)[None, :] * np.ones((H, 1), np.float32)
    broad = _noise2(rng, W, H, 9, 7) - 0.5
    fine = _noise2(rng, W, H, 90, 16) - 0.5
    lw = lat + broad * warp * 2.0 + fine * warp * 0.7
    if festoon:                                           # song tren ranh gioi dai (festoon)
        fl, amp, k = festoon
        lw += amp * np.exp(-((lat - fl) / 3.0) ** 2) * np.sin(lon * k + broad * 9.0)
    ys = np.array([t[0] for t in table], np.float32)
    order = np.argsort(ys)
    ys = ys[order]
    cols = np.array([table[i][1] for i in order], np.float32)
    out = np.empty((H, W, 3), np.float32)
    for c in range(3):
        out[..., c] = np.interp(lw.ravel(), ys, cols[:, c]).reshape(H, W)
    st = _noise2(rng, W, H, 140, 44)
    out *= (1.0 - streak + 2 * streak * st)[..., None]
    return out, lat, lon


