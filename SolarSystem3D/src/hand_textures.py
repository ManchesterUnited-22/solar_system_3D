def mars_texture(out_w=2048, out_h=1024, seed=21):
    rng = np.random.default_rng(seed)
    W, H = out_w, out_h
    cv = _Canvas(W, H)
    n_big, n_mid, n_fine = _fbm(rng, W, H, 9, 5), _fbm(rng, W, H, 50, 4), _fbm(rng, W, H, 220, 3)
    lat = np.linspace(90, -90, H, dtype=np.float32)[:, None] * np.ones((1, W), np.float32)
    alat = np.abs(lat)
    img = _mix((0.58, 0.29, 0.15), (0.84, 0.50, 0.28), 0.55 * n_big + 0.45 * n_mid)
    for lon, la, rx, ry, rot, k in MARS_DARK:
        m = cv.layer(polys=[_fractal(_ellipse(lon, la, rx, ry, rot), rng, 3, 0.2)], blur=0.9 * W / 360.0)
        m = _smooth(0.32, 0.64, m + (n_mid - 0.5) * 0.9 + (n_fine - 0.5) * 0.4)
        img = _mix(img, _mix((0.28, 0.16, 0.11), (0.48, 0.28, 0.19), n_fine), m * k)
    for lon, la, rx, ry, col in MARS_LIGHT:
        m = cv.layer(polys=[_fractal(_ellipse(lon, la, rx, ry), rng, 3, 0.15)], blur=0.8 * W / 360.0)
        img = _mix(img, col, _smooth(0.25, 0.8, m) * 0.85)
    # Vastitas Borealis: dai toi o Bac ban cau
    img = _mix(img, (0.40, 0.25, 0.18), _smooth(52, 68, lat + (n_mid - 0.5) * 10) * _smooth(88, 80, alat) * 0.6)
    # Valles Marineris + Olympus
    vm = [_fractal([(-90, -11), (-80, -13), (-70, -13.5), (-60, -12), (-55, -10)], rng, 3, 0.10, False)]
    canyon = cv.layer(lines=[(v, 1.4) for v in vm], blur=0.4 * W / 360.0)
    img = _mix(img, (0.30, 0.15, 0.10), np.clip(canyon * 1.4, 0, 1) * 0.9)
    img *= (0.90 + 0.20 * n_fine)[..., None]
    _craters(img, rng, 1600, 0.25, 3.5, 0.18, 0.07)
    # chom bang cuc, vanh toi quanh chom Bac
    edge = (n_mid - 0.5) * 6.0
    img = _mix(img, (0.34, 0.22, 0.17), np.exp(-((lat - 80.0 + edge) / 2.0) ** 2) * 0.5)
    cap_n = _smooth(83.0, 85.5, lat + edge)
    cap_s = _smooth(-81.5, -84.0, lat - edge)
    img = _mix(img, (0.96, 0.96, 0.98), np.clip(cap_n + cap_s, 0, 1))
    return _finish(img)


